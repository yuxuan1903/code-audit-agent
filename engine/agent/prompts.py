TRUNCATION_CONTINUE = """\
[输出被长度上限截断] 你上一条回复没有输出完。请从中断处继续，
不要再重复已经说过的内容。若还有工具要调用，直接调用。
"""

# ★ 下面两段是给**截断残骸**用的，措辞是核心，不能图省事复用参数校验的报错。
#
# 残骸块（参数为 `{}`）如果当普通调用执行，注册表会回一句
# "参数校验失败：缺少必填参数" —— 模型收到这句话，**唯一合理的理解就是
# "我把参数写错了"**。实测它真的这么想了：`real-group` 第 35 轮的思考原文是
# "the previous attempt dropped because I emitted an empty call"。
# 于是它花轮次重发、把预算烧在自我纠正上，而它本来要记的东西可能就此丢失。
#
# 事实是：它什么都没写错，是单轮输出长度不够。反馈必须说出这一点，
# 并给出**可执行**的补救（下一轮发少几个），否则模型只能靠猜。

TOOL_REMNANT = """\
⚠️ 这个调用（`{name}`）**没有执行**。原因不是参数写错——是上一条回复被
输出长度上限截断，这个调用排在刀口上，参数**没有传完**，所以收到的是空的。
不用道歉、不用解释，按下面的办法重发即可。\
"""


def truncation_notice(n_calls: int, n_exec: int, n_remnant: int,
                      n_parse: int = 0) -> str:
    """整批的截断说明，接在 tool_result 之后一起回给模型。

    ★ `n_exec` 必须说清楚，否则模型会以为整批都没成、把**已经执行过**的重发
    一遍——那些副作用（往账本里写发现、标候选已处置）就写重了。
      `n_exec` 是"执行过"而不是"成功"：写重账本取决于有没有执行，不取决于
      成功与否（失败的那次可能也改了状态）。
    ★ 补救要给**可执行的数字**——"少发一些"模型没法照做，"一轮 3 个以内"可以。
    """
    parts = [
        f"[本轮输出被长度上限截断] 你发出了 {n_calls} 个调用："
        f"**{n_exec} 个参数完整、已经执行**（结果见上），"
        f"**{n_remnant} 个没传完、已跳过**。"
        "被跳过**不是**你把参数写错了，是单轮输出长度不够，别去改参数。"
    ]
    if n_parse:
        parts.append(f"另有 {n_parse} 个调用因参数不是合法 JSON 被拒，那是另一回事。")
    parts.append(
        f"补救：把没传完的那几个**拆到下一轮再发**，下一轮控制在 "
        f"{max(1, min(n_exec, 4))} 个调用以内；每个调用里的长文本字段"
        "（证据、说明）也适当精简。**已经执行过的不要重发。**"
    )
    return "\n".join(parts)


def nudge_for(ratio: float, cfg) -> str | None:
    """按预算比例选提示词。返回 None 表示不提示。"""
    if ratio >= cfg.agent.final_at_ratio:
        return NUDGE_FINAL
    if ratio >= cfg.agent.converge_at_ratio:
        return NUDGE_CONVERGE
    if ratio >= cfg.agent.nudge_at_ratio:
        return NUDGE_HALF
    return None
